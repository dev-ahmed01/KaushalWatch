"""Scorecard provenance gate for final (non-synthetic) evaluation.

The media manifest supplies file identity. This module adds *row-level*
validation before the scorer can turn a spreadsheet into apparently credible
metrics. It does not prove that a manually supplied prediction was actually
generated by a model: that requires independently retained inference logs.
"""
from __future__ import annotations

import csv
import hashlib
import json
import re
import sys
from pathlib import Path
from typing import Mapping

ROOT = Path(__file__).resolve().parents[1]
BACKEND = ROOT / "backend"
if str(BACKEND) not in sys.path:
    sys.path.insert(0, str(BACKEND))

from app.services.release_assets import qualify_release_assets

KINDS = ("attendance", "equipment", "operability", "cases")
VALID_BOOL = {"true", "false", "1", "0", "yes", "no", "y", "n"}
TRUTH_STATES = {"APPARENTLY_ACTIVE", "APPARENTLY_INACTIVE"}
PRED_STATES = TRUTH_STATES | {"UNCERTAIN"}
SHA_PATTERN = re.compile(r"^[0-9a-f]{64}$")


def _strict_bool(value: str, field: str) -> bool:
    text = str(value).strip().lower()
    if text not in VALID_BOOL:
        raise ValueError(f"{field}: expected a true/false label, got {value!r}")
    return text in {"true", "1", "yes", "y"}


def _nonnegative_int(value: str, field: str) -> int:
    try:
        integer = int(str(value).strip())
    except (ValueError, TypeError) as exc:
        raise ValueError(f"{field}: expected a nonnegative integer") from exc
    if integer < 0:
        raise ValueError(f"{field}: count cannot be negative")
    return integer


def _inspect_rows(kind: str, path: Path) -> dict:
    with path.open("r", newline="", encoding="utf-8-sig") as handle:
        reader = csv.DictReader(handle, strict=True)
        if not reader.fieldnames or len(reader.fieldnames) != len(set(reader.fieldnames)):
            raise ValueError(f"{kind}: missing or duplicate CSV column names")
        rows = list(reader)

    if not rows:
        raise ValueError(f"{kind}: no labelled rows")
    seen: set[tuple[str, ...]] = set()
    positives = 0
    negatives = 0
    classes: dict[str, dict[str, int]] = {}

    for number, row in enumerate(rows, start=2):
        def field(column: str) -> str:
            value = row.get(column)
            if value is None or not str(value).strip():
                raise ValueError(f"{kind}:{number}: missing {column}")
            return str(value).strip()

        sample_id = field("sample_id")
        if kind in {"equipment", "operability"}:
            item_id = field("item_id")
            key = (sample_id, item_id)
        elif kind == "cases":
            key = (sample_id, field("case_type"))
        else:
            key = (sample_id,)
        if key in seen:
            raise ValueError(f"{kind}:{number}: duplicated scoring opportunity {key}")
        seen.add(key)

        if kind in {"attendance", "equipment"}:
            _nonnegative_int(field("true_count"), f"{kind}:{number}.true_count")
            _nonnegative_int(field("pred_count"), f"{kind}:{number}.pred_count")
        if kind in {"attendance", "cases"}:
            truth = _strict_bool(field("true_issue"), f"{kind}:{number}.true_issue")
            _strict_bool(field("pred_issue"), f"{kind}:{number}.pred_issue")
            positives += int(truth)
            negatives += int(not truth)
            if kind == "cases":
                category = field("case_type")
                support = classes.setdefault(category, {"positive": 0, "negative": 0})
                support["positive" if truth else "negative"] += 1
        if kind == "operability":
            if field("true_state").upper() not in TRUTH_STATES:
                raise ValueError(f"{kind}:{number}: invalid ground-truth state")
            if field("pred_state").upper() not in PRED_STATES:
                raise ValueError(f"{kind}:{number}: invalid predicted state")

    if kind == "cases" and not (positives and negatives):
        raise ValueError("cases: require both actual positive and negative case opportunities")

    return {
        "sample_rows": len(rows),
        "ground_truth_positive": positives if kind in {"attendance", "cases"} else None,
        "ground_truth_negative": negatives if kind in {"attendance", "cases"} else None,
        "per_case_type_support": classes if kind == "cases" else None,
    }


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def verify_frozen_scorecard_inputs(manifest_path: Path, csv_paths: Mapping[str, str | Path]) -> dict:
    """Raise ValueError before any report is written if a final source drifts."""
    manifest_path = Path(manifest_path).expanduser().resolve()
    qualification = qualify_release_assets(manifest_path)
    if not qualification["ready"]:
        failed = [x["check"] for x in qualification["checks"] if not x["ok"]]
        raise ValueError("Release manifest is not qualified: " + ", ".join(failed))

    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    entries = {item["kind"]: item for item in manifest["annotations"]}
    if set(csv_paths) != set(KINDS) or set(entries) != set(KINDS):
        raise ValueError("The final scorecard requires all four frozen annotation kinds")

    inputs: dict[str, dict] = {}
    for kind in KINDS:
        chosen = Path(csv_paths[kind]).expanduser().resolve()
        registered = Path(entries[kind]["path"]).expanduser()
        if not registered.is_absolute():
            registered = manifest_path.parent / registered
        registered = registered.resolve()
        if chosen != registered:
            raise ValueError(f"{kind}: provided CSV is not the frozen manifest source")
        digest = _sha256(chosen)
        expected = entries[kind]["sha256"].lower()
        if not SHA_PATTERN.fullmatch(expected) or digest != expected:
            raise ValueError(f"{kind}: source changed after freeze")
        info = _inspect_rows(kind, chosen)
        inputs[kind] = {"sha256": digest, **info}

    clips = {
        item["role"]: item["sha256"].lower()
        for item in manifest["assets"]
    }
    return {
        "qualification": "passed_file_integrity_and_scoring_schema_checks",
        "manifest_sha256": qualification["manifest_sha256"],
        "scenario_sha256": manifest["scenario"]["sha256"].lower(),
        "source_video_sha256_by_role": clips,
        "annotation_inputs": inputs,
        "prediction_provenance": (
            "Prediction columns were provided in frozen CSVs. This scorer verifies "
            "their integrity and valid domain, NOT that values came from the claimed "
            "model or were generated independently of ground truth."
        ),
    }
